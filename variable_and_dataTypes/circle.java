public class circle {
    public static void main(String[] args) {
        
        double pi =3.14159;
        double r = 14;
        double c= 2*pi*r;
        double area= pi*r*r;

        System.out.println("Circumference of a circle : "+c);
        System.out.println("Area of a circle : "+area);

    }
}
