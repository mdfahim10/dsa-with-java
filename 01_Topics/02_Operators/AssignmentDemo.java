public class AssignmentDemo {
    public static void main(String[] args) {

        int x = 20;

        x += 5;     // x=x+5 x =25
        x -= 2;     // x=25-2 x=23
        x *= 3;     // x=23*3 x=69
        x /= 4;     // x=69/4 x=17
        x %= 5;     // x=17%5 x=2

        System.out.println(x); //x=2
    }
}