
public class EvenOrOdd {
    public static void main(String[] args) {
        int n = 101;
        if (n != 0) {
            if (n % 2 == 0) {
                System.out.println("Even");
            } else {
                System.out.println("Odd");
            }
        } else {
            System.out.println("Neithet Even nor Odd");
        }
    }
}
